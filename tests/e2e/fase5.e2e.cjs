    await navegar(j, 'Funil de negócios')
    await j.getByRole('region', { name: 'Contrato' }).getByRole('listitem').first().click()
    await j.getByRole('button', { name: /^Atividades/ }).click()
    await j.getByRole('button', { name: 'Nova atividade' }).click()
    d = j.getByRole('dialog')
    await d.getByLabel('Título').fill('Acompanhar registro da escritura')
    await d.getByRole('button', { name: 'Agendar' }).click()
    await j.getByText('Atividade agendada.').first().waitFor()
    await j.getByRole('button', { name: 'Venda', exact: true }).click()
    await j.getByRole('button', { name: 'Escriturada' }).click()
