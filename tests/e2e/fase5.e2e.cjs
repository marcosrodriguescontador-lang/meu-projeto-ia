    await foto(j, '44-agenda')
    await navegar(j, 'Indicadores')
    await j.getByRole('table', { name: 'Funil de conversão' }).waitFor()
    await foto(j, '45-indicadores-conversao')
    await navegar(j, 'Contas bancárias')
    await j.getByRole('button', { name: 'Verificar razão' }).click()
