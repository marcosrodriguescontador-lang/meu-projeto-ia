    await j.keyboard.press('Escape')
    await navegar(j, 'Contas a pagar')
    await j.getByRole('cell', { name: /Comissão \(captador 20%\)/ }).waitFor()
    await j.getByRole('cell', { name: /Comissão \(vendedor 30%\)/ }).waitFor()
    await navegar(j, 'Comissões')
