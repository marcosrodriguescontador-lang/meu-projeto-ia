// Teste E2E da Fase 4 (financeiro completo: extratos, conciliação, transferências, despesas, fluxo e relatórios).
const { mkdtempSync, rmSync, readFileSync, writeFileSync, copyFileSync, existsSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const assert = require('node:assert/strict')
const { abrir, foto, configurar, entrar, simularDialogos, navegar, novaPessoa, novoImovel, SAIDA } = require('./comum.cjs')

const hoje = new Date().toLocaleDateString('sv-SE')
const ofx = (transacoes, saldo) =>
  `OFXHEADER:100\nDATA:OFXSGML\n\n<OFX><BANKMSGSRSV1><STMTTRNRS><STMTRS><BANKACCTFROM><BANKID>0341<ACCTID>12345-6</BANKACCTFROM><BANKTRANLIST>\n${transacoes
    .map((t) => `<STMTTRN><TRNTYPE>OTHER<DTPOSTED>${hoje.replace(/-/g, '')}<TRNAMT>${t.valor}<FITID>${t.fitid}<MEMO>${t.memo}</STMTTRN>`)
    .join('\n')}\n</BANKTRANLIST><LEDGERBAL><BALAMT>${saldo}<DTASOF>${hoje.replace(/-/g, '')}</LEDGERBAL></STMTRS></STMTTRNRS></BANKMSGSRSV1></OFX>`
const aguardarArquivo = async (f) => {
  for (let i = 0; i < 60 && !existsSync(f); i++) await new Promise((r) => setTimeout(r, 500))
  assert.ok(existsSync(f), `arquivo não gerado: ${f}`)
}
const reais = (texto) => Number(texto.replace(/[^\d,]/g, '').replace(',', '.'))

;(async () => {
  const dados = mkdtempSync(join(tmpdir(), 'status-e2e4-'))
  const { app, janela: j } = await abrir(dados)
  try {
    await configurar(j)
    await entrar(j)
    await novaPessoa(j, { nome: 'Maria da Silva Souza', cpf: '529.982.247-25', papel: 'Proprietário' })
    await novaPessoa(j, { nome: 'Carlos Locatário', cpf: '390.533.447-05', papel: 'Locatário' })
    await novaPessoa(j, { nome: 'Fornecedor Geral', cpf: '111.444.777-35', papel: 'Fornecedor' })
    await novoImovel(j, { proprietario: 'Maria da Silva Souza', logradouro: 'Rua Barão de Jaguara', numero: '1200', bairro: 'Centro', cidade: 'Campinas', aluguel: '2500' })

    // 1. Contas: terceiros e própria
    await navegar(j, 'Contas bancárias')
    for (const [nome, tit] of [['Itaú — recursos de terceiros', 'TERCEIROS'], ['Itaú — conta própria', 'PROPRIO']]) {
      await j.getByRole('button', { name: 'Nova conta' }).click()
      await j.getByLabel('Nome').fill(nome)
      await j.getByLabel('Titularidade dos recursos').selectOption(tit)
      await j.getByLabel('Saldo inicial', { exact: true }).fill(tit === 'PROPRIO' ? '1000' : '0')
      await j.getByLabel('Data do saldo inicial').fill('2026-07-01')
      await j.getByRole('dialog').getByRole('button', { name: 'Salvar' }).click()
      await j.getByText('Conta salva.').first().waitFor()
      await j.getByRole('dialog').waitFor({ state: 'detached' })
    }

    // 2. Contrato, cobrança de setembro e recebimento
    await navegar(j, 'Locações')
    await j.getByRole('button', { name: 'Novo contrato' }).click()
    await j.getByPlaceholder(/Buscar imóvel com oferta de locação/).fill('Barão')
    await j.getByRole('button', { name: /Rua Barão de Jaguara/ }).click()
    await j.getByPlaceholder(/Buscar pessoa para vincular/).first().fill('Carlos')
    await j.getByRole('button', { name: /Carlos Locatário/ }).click()
    await j.getByLabel('Início').fill('2026-08-01')
    await j.getByLabel('Prazo (meses)').fill('30')
    await j.getByLabel('Modalidade').selectOption('SEM_GARANTIA')
    await j.getByRole('button', { name: 'Salvar' }).click()
    await j.getByText('Contrato criado como rascunho.').first().waitFor()
    await j.getByRole('button', { name: 'Ativar contrato' }).click()
    await j.getByRole('dialog').getByRole('button', { name: 'Ativar' }).click()
    await j.getByText('Contrato ativado.').first().waitFor()
    await navegar(j, 'Cobranças do mês')
    await j.locator('input[type=month]').fill('2026-09')
    await j.getByRole('button', { name: /Gerar 1 cobrança/ }).click()
    await j.getByText(/1 cobrança\(s\) gerada\(s\)/).first().waitFor()
    await navegar(j, 'Contas a receber')
    await j.getByRole('cell', { name: /Aluguel set\/2026/ }).click()
    await j.getByRole('button', { name: 'Registrar recebimento' }).click()
    await j.getByText('Total devido').waitFor()
    await j.getByLabel('Conta de destino').selectOption({ label: 'Itaú — recursos de terceiros (terceiros)' })
    await j.getByRole('button', { name: 'Confirmar recebimento' }).click()
    const toastReceb = await j.getByText(/Recebimento de R\$/).first().textContent()
    const recebido = reais(toastReceb.match(/R\$\s*[\d.,]+/)[0])
    await j.keyboard.press('Escape')

    // 3. Importação de OFX: crédito do aluguel (conciliado automaticamente) e tarifa sem par
    const arquivo = join(dados, 'extrato-itau.ofx')
    writeFileSync(arquivo, ofx([{ valor: recebido.toFixed(2), fitid: 'E2E-1', memo: 'PIX RECEBIDO CARLOS' }, { valor: '-12.50', fitid: 'E2E-2', memo: 'TARIFA PACOTE SERVICOS' }], (recebido - 12.5).toFixed(2)), 'latin1')
    await navegar(j, 'Contas bancárias')
    await j.getByRole('cell', { name: /Itaú — recursos de terceiros/ }).click()
    await simularDialogos(app, { abrir: [arquivo] })
    await j.getByRole('button', { name: 'Importar extrato (OFX/CSV)' }).click()
    await j.getByText(/2 transação\(ões\) nova\(s\).*1 conciliada\(s\) automaticamente/).first().waitFor()
    await j.getByText('TARIFA PACOTE SERVICOS').waitFor()
    await foto(j, '27-conciliacao-pendente')
    // Mesmo arquivo de novo: recusado, nada duplicado
    await j.getByRole('button', { name: 'Importar extrato (OFX/CSV)' }).click()
    await j.getByText('Este arquivo já foi importado para esta conta.').first().waitFor()
    // Tarifa lançada como despesa a partir da linha do extrato
    await j.getByTitle('Lançar no sistema (tarifa, rendimento…)').click()
    const dlg = j.getByRole('dialog')
    await dlg.getByPlaceholder(/Buscar pessoa para vincular/).fill('Forne')
    await dlg.getByRole('button', { name: /Fornecedor Geral/ }).click()
    await dlg.getByLabel('Categoria').selectOption({ label: '4.3.01 — Despesa — tarifas bancárias' })
    await dlg.getByRole('button', { name: 'Lançar e conciliar' }).click()
    await j.getByText('Lançado e conciliado.').first().waitFor()
    await j.getByText('Diferença na data do extrato').locator('..').getByText('R$ 0,00').waitFor()
    await j.getByRole('combobox', { name: 'Situação' }).selectOption('')
    await j.getByText('Conciliada (automática)').waitFor()
    await foto(j, '28-conciliacao-concluida')

    // 4. Transferência das taxas para a conta própria (bloqueia valores de terceiros)
    await navegar(j, 'Contas bancárias')
    await j.getByText('Separação de recursos').waitFor()
    await foto(j, '29-separacao-recursos')
    await j.getByRole('button', { name: 'Transferir entre contas' }).click()
    await j.getByRole('dialog').getByLabel('Valor', { exact: true }).fill('2000')
    await j.getByRole('dialog').getByLabel('Descrição', { exact: true }).fill('Taxas de administração')
    await j.getByRole('dialog').getByRole('button', { name: 'Transferir' }).click()
    await j.getByRole('dialog').getByText(/recursos de terceiros/).last().waitFor()
    await j.getByRole('dialog').getByLabel('Valor', { exact: true }).fill('100')
    await j.getByRole('dialog').getByRole('button', { name: 'Transferir' }).click()
    await j.getByText('Transferência registrada.').first().waitFor()

    // 5. Despesa da imobiliária, já paga pela conta própria
    await navegar(j, 'Contas a pagar')
    await j.getByRole('button', { name: 'Nova despesa' }).click()
    const d2 = j.getByRole('dialog')
    await d2.getByPlaceholder(/Buscar pessoa para vincular/).fill('Forne')
    await d2.getByRole('button', { name: /Fornecedor Geral/ }).click()
    await d2.getByLabel('Categoria').selectOption({ label: '4.2.03 — Despesa — sistemas, internet e tecnologia' })
    await d2.getByLabel('Descrição', { exact: true }).fill('Internet do escritório')
    await d2.getByLabel('Valor', { exact: true }).fill('149,90')
    await d2.getByLabel('Já foi paga').check()
    await d2.getByLabel('Conta', { exact: true }).selectOption({ label: 'Itaú — conta própria (próprio)' })
    await foto(j, '30-nova-despesa')
    await d2.getByRole('button', { name: 'Registrar' }).click()
    await j.getByText('Lançamento registrado e quitado.').first().waitFor()

    // 6. Fluxo de caixa, relatórios (prévia + PDF + Excel), painel com gráfico
    await navegar(j, 'Fluxo de caixa')
    await j.getByText('Entradas e saídas por mês').first().waitFor()
    await foto(j, '31-fluxo-caixa')
    await navegar(j, 'Relatórios')
    await j.getByRole('button', { name: 'Resultado gerencial mensal' }).click()
    await j.getByRole('cell', { name: /Resultado/ }).first().waitFor()
    await foto(j, '32-relatorio-resultado')
    const xlsx = join(dados, 'resultado.xlsx')
    await simularDialogos(app, { salvar: xlsx })
    await j.getByRole('button', { name: 'Excel' }).click()
    await aguardarArquivo(xlsx)
    assert.equal(readFileSync(xlsx).subarray(0, 2).toString(), 'PK')
    await j.getByRole('button', { name: 'Valores a repassar aos proprietários' }).click()
    await j.getByText(/confere com o saldo/).waitFor()
    await foto(j, '33-relatorio-repassar')
    await j.getByRole('button', { name: 'Base para a DIMOB (locações)' }).click()
    await j.getByRole('cell', { name: 'Maria da Silva Souza' }).first().waitFor()
    const pdf = join(dados, 'dimob.pdf')
    await simularDialogos(app, { salvar: pdf })
    await j.getByRole('button', { name: 'PDF' }).click()
    await aguardarArquivo(pdf)
    assert.equal(readFileSync(pdf).subarray(0, 4).toString(), '%PDF')
    copyFileSync(pdf, join(SAIDA, 'relatorio-dimob-exemplo.pdf'))
    await foto(j, '34-relatorio-dimob')
    await navegar(j, 'Contas bancárias')
    await j.getByRole('button', { name: 'Verificar razão' }).click()
    await j.getByText(/Razão íntegro/).waitFor()
    await navegar(j, 'Painel')
    await j.getByText(/Receitas próprias e despesas da imobiliária/).waitFor()
    await foto(j, '35-painel-graficos')
    console.log('E2E Fase 4: OK — capturas em', SAIDA)
  } catch (e) {
    await foto(j, 'erro-fase4').catch(() => {})
    console.error('E2E Fase 4: FALHOU', e)
    process.exitCode = 1
  } finally {
    await app.close().catch(() => {})
    rmSync(dados, { recursive: true, force: true })
  }
})()
